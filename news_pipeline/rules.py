def hits(text: str, phrases: List[str]) -> List[str]:
    t = text or ""
    return [p for p in phrases if p and p in t]


def mass_verdict(item, strictness: str = "strict") -> Tuple[bool, List[str], List[str], str]:
    """大众贴近度准入：先 reject_mass，再 keep_mass；逐条留痕。"""
    if strictness == "off":
        return True, ["档位 off：本层不启用"], [], "通过（贴近度层关闭）"
    text = item.text()
    instant = hits(text, INSTANT_ACTION)
    if instant:
        return True, [f"即时民生保护:{h}" for h in instant[:5]], [], \
            "通过（即时可行动民生信息一律保留，剔除看稿件性质不看发布主体）"
    reject: List[str] = []
    for name, phrases in (("ACHIEVEMENT_STRONG", ACHIEVEMENT_STRONG),
                          ("FAR_FUTURE", FAR_FUTURE), ("UNRELATED", UNRELATED)):
        hs = hits(text, phrases)
        if hs:
            if name == "FAR_FUTURE" and hits(text, FUTURE_EXEMPT):
                continue
            # 01 第二节 / 00 §7 坑 7：带单位数字不能救下成就宣传稿。
            # 只有同时命中「明确受影响对象」+「即时可行动」词组才豁免；
            # 单纯的「416464亿元、同比增长1.0%」不是保留理由。
            if name == "ACHIEVEMENT_STRONG" and hits(text, AFFECTED_OBJECTS) \
                    and hits(text, INSTANT_ACTION):
                continue
            reject.extend([f"{name}:{h}" for h in hs])
    if reject:
        return False, [], reject, f"三类强剔除命中：{'、'.join(reject[:4])}"
    # 01 §4.1.2：国际仅三类重大突发。这些条目是全民性重大突发，必须在贴近度层
    # 通过，否则「大众贴近度 → 国际门禁」的顺序会把战争 / 灾害 / 突发事故全部前置剔光。
    three = [f"{tag}:{p}" for tag, ps in INTL_THREE.items() for p in hits(text, ps)]
    if three:
        return True, [f"三类重大突发:{h}" for h in three[:5]], [], \
            "通过（三类重大突发 / 全民性热点，01 §4.1.2；国际门禁仍逐条复核）"
    keep: List[str] = []
    for group, phrases in MASS_TOPIC.items():
        hs = hits(text, phrases)
        keep.extend([f"{group}:{h}" for h in hs])
    keep += [f"NATIONAL_HOT:{h}" for h in hits(text, NATIONAL_HOT)]
    # SKILL §1.5 / §4.1.3 只有三档：strict（默认，未命中 reject 也未命中 keep 即剔）、
