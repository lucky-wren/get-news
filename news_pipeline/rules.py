def bankruptcy_subject_verdict(it) -> tuple[bool, str, str]:
    """需求④：破产倒闭只留上市 / 知名 / 规模可核对的主体。

    返回 (是否通过, 主体类型, 依据)。非破产倒闭条目直接通过。
    判定全用可核对词组与带单位数字，禁用「影响大 / 重大」主观词。
    """
    t = it.text()
    hit = [w for w in BANKRUPTCY_WORDS if w in t]
    if not hit:
        return True, "—", "非破产倒闭类条目，不适用"
    listed = [w for w in LISTED_SIGNALS if w in t]
    known = [w for w in KNOWN_SIGNALS if w in t]
    scale = SCALE_NUM.findall(t)
    if listed:
        return True, "上市主体", f"命中上市信号：{'、'.join(listed[:4])}"
    vague = hits(t, VAGUE_SUBJECT)
    # 需求④「规模可核对」：有带单位规模数字 + 主体不是模糊说法即通过，
    # 不要求同时命中多条知名主体信号（真实稿件常只写「某知名车企」）。
    if scale and not vague:
        return True, "规模可核对", (f"带单位规模数字 {'、'.join(scale[:3])}；"
                                 f"主体信号 {'、'.join(known[:3]) or '标题含明确主体'}；无模糊主体词")
    if known and len(known) >= 2 and not vague:
        return True, "知名主体", f"命中知名主体信号：{'、'.join(known[:4])}"
    return False, "主体不可核对", (
        f"命中破产倒闭词组「{'、'.join(hit[:3])}」，但未命中上市信号、"
        f"无带单位规模数字、知名主体信号不足 2 个；按需求④剔除并留痕")
