    # 真实批次里新出现的合规表述应补进 MASS_TOPIC，而不是放宽判定式。
    if keep or strictness == "moderate":
        return True, keep, [], ("通过（正面清单 / 全民性热点命中）" if keep
                                else "通过（moderate 档：未命中三类强剔除，放宽通过）")
    return False, [], [], "未命中正面清单与全民性热点，strict 档剔除"


