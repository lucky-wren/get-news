def _align(group: str, tag: str, legacy: bool = False) -> Tuple[str, str]:
    """硬约束：分类标签前缀必须等于上位大类，杜绝「民生服务 + 国际动态/…」错配。

    legacy=true 时保留台账里的扩展大类原值（如「工厂与制造业」「社会治理」），
    对齐目标态样例；默认 false 时统一收敛到 SKILL 的 8 个上位大类。
    """
    pre = (tag or "").split("/")[0].strip()
    if pre in GROUPS_8 and pre == (group or pre):
        return pre, tag
    if not group:
        group = "民生服务"
    elif not legacy and group not in GROUPS_8:
        group = "民生服务"
    # 2026-11-21 全面核查：旧版对「房地产 / 地方债务」「交通出行 / 天气」这类
    # 含斜杠的细标签直接返回 (财经市场, 房地产 / 地方债务)，前缀 ≠ 上位大类，
    # 实测 2/75 条分类不合规。01 §3「上位大类与分类标签合规」要求含斜杠的
    # 细标签首段必须等于上位大类，这里统一补前缀；不带斜杠的细标签按规格保留。
    t = (tag or "").strip()
    if not t or t == "综合":
        return group, t or "综合"
    parts = [p.strip() for p in t.split("/") if p.strip()]
    if parts and parts[0] == group:
        return group, " / ".join(parts)
    return group, " / ".join([group] + parts)


def classify(item, legacy: bool = False) -> Tuple[str, str]:
    """上位大类与细标签。

    修订要点（针对实测数据里 10/50 条错配）：
      1. 采集源显式 tag 若挂「国际动态」但标题无境外信号 / 命中伪友好词 → 撤销，走国内分类；
      2. 返回前强制 group 与 tag 前缀一致；
      3. 国际三类标签必须有境外地理或国际组织信号，「经济地震」「生活大爆炸」不得命中。
    """
    group = item.group or ""
    if not legacy:
        if group in GROUP_ALIAS:
            group = GROUP_ALIAS[group]
        if group and group not in GROUPS_8:
            group = "民生服务"
    title = item.title or ""
    geo = bool(hits(title, INTL_GEO_SIGNAL) or hits(item.source or "", INTL_GEO_SIGNAL))
    ff = hits(title, FALSE_FRIENDS)
    if not group:
        group = "国际动态" if (geo and not ff) else "民生服务"

    tag = (item.tag or "").strip()
    if tag.startswith("国际动态") and (not geo or ff):
        tag = ""                       # 撤销误挂，重新按国内规则分类

    if tag:
        return _align(group, tag, legacy)

    text = item.text()
    # 国内防灾科普优先回落，避免被「地震」二字拖进国际灾害标签
    if hits(title, DOMESTIC_SAFETY[2]):
        return _align(group, DOMESTIC_SAFETY[1], legacy)
    for g, t, phrases in TAG_RULES:
        if not phrases:
            continue
        if t.startswith("国际动态"):
            if not geo or ff or any(p in ff for p in phrases):
                continue
            if hits(text, phrases):
                return _align(g, t, legacy)
        elif hits(title, phrases):
            return _align(g if g in GROUPS_8 else group, t, legacy)
    # 2026-11-21 修复：旧版「只要 geo 为真就无脑挂灾害与公共卫生」，导致
    # 习近平会见外国总理、CNCERT 机构介绍 / 旧漏洞公告全挂成
    # 「国际动态 / 灾害与公共卫生」（用户 xlsx 649/655-658/725-732 实测）。
    # 现在必须命中对应三类的词组才给三类标签，否则回落「综合」，
    # 由 intl_verdict 按「国际只留战争/灾害/突发事故」逐条剔除。
    if group == "国际动态" and geo:
        for g, t, phrases in TAG_RULES:
            if t.startswith("国际动态") and phrases and hits(text, phrases):
                return _align(g, t, legacy)
        return _align(group, "综合", legacy)
    return _align(group, "综合", legacy)


def story_key(item) -> str:
    """议题名：硬编码重大事件 → 通用主题词。命中即收敛，不要求主体+动作，
    因为「A股低价股退市潮」里每条主体都不同，硬编码主体必然漏合并。"""
    for t in STORY_TOPICS:
        subj = hits(item.title, t["subjects"])
        if not subj:
            continue
        acts = hits(item.title, t["actions"]) + hits(item.abstract, t["actions"])
        if len(set(subj + acts)) >= 2:
            return t["name"]
    for name, phrases in TOPIC_THEMES:
        if hits(item.title, phrases):
            return name
    return ""


