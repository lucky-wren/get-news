def func_tier(item) -> Tuple[str, int, int, int, str]:
    """信息功能档位：返回 (档位名, ΔI, cap, ΔC, C 档位名)。单条取最高一档。"""
    text = item.text()
    best = ("", 0, 0, [], 0)
    for name, delta, cap, phrases in FUNC_TIERS:
        hs = hits(text, phrases)
        # 「突破 / 首次 / 发布」需已实现成果，剔除否定式
        if name == "科技 / 工程突破" and not hs:
            continue
        if hs and (delta > best[1] or (delta == best[1] and cap > best[2])):
            best = (name, delta, cap, hs, 0)
    c_name, c_delta = "", 0
    for name, delta, phrases in C_TIERS:
        if hits(text, phrases):
            c_name, c_delta = name, delta
            break
    # 便民档 cap 由「仅 C 维度有加分」触发
    cap = best[2]
    if best[0] == "便民服务 / 生活提示" and c_delta > 0:
        cap = 2
    return best[0], best[1], cap, c_delta, c_name


def daily_groups(item) -> Tuple[List[str], int, float]:
    groups, total = [], 0
    text = item.text()
    for g, phrases in TABLE_R.items():
        hs = hits(text, phrases)
        if hs:
            groups.append(g)
            total += len(hs)
    return groups, total, min(12.0, 4 * len(groups) + min(4, total))


